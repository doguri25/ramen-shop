type Row = [name: string, note: string, color: string, shape: string, color2?: string];
function shopItems(kind: MiniKind, steps: CStep[], rows: [Row[], Row[], Row[]]): CItem[] {
  const pairs = [PA, PB, PC];
  return rows.flatMap((list, si) => list.map(([name, note, color, shape, color2], i) => ({
    id: `${kind}_${steps[si].id}_${i}`, kind, step: steps[si].id, name, effects: [...pairs[si][i]], note, color, color2, shape,
  })));
}
